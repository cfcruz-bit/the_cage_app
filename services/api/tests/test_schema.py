@pytest.mark.asyncio
async def test_las_claves_foraneas_estan_activas(session: AsyncSession) -> None:
    """Guardia del propio banco de pruebas.

    SQLite ignora las FK salvo que se pidan por conexion. Si este test falla,
    todos los de CASCADE de arriba estan pasando sin probar nada.
    """
    result = await session.execute(text("PRAGMA foreign_keys"))
    assert result.scalar() == 1

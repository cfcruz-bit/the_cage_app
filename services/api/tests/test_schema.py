@pytest.mark.asyncio
async def test_la_migracion_crea_todas_las_tablas(session: AsyncSession) -> None:
    conn = await session.connection()
    names = await conn.run_sync(lambda c: set(inspect(c).get_table_names()))
    assert names == EXPECTED_TABLES


def test_los_modelos_no_se_han_separado_de_las_migraciones(database_url: str) -> None:
    """El test que evita el fallo mas caro de todos.

    Si alguien anade una columna a un modelo y olvida generar la migracion, la
    aplicacion funciona en su maquina y revienta en produccion. `alembic check`
    compara los modelos contra la base migrada y falla si sobra o falta algo.
    """
    try:
        command.check(_alembic_config(database_url))
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - solo al fallar
        pytest.fail(
            "Los modelos y las migraciones han divergido. Genera la revision "
            f"con `alembic revision --autogenerate`.\n{exc}"
        )


# ── Helpers ──────────────────────────────────────────────────────────────────


def _user(role: UserRole = UserRole.ATHLETE, email: str | None = None) -> User:
    suffix = uuid.uuid4().hex[:8]
    return User(
        email=email if email is not None else f"{suffix}@cage.test",
        password_hash="argon2-fake",
        display_name="Test",
        role=role.value,
    )


async def _meso_con_ejercicio(
    session: AsyncSession,
) -> tuple[Mesocycle, MesocycleExercise]:
    coach = _user(UserRole.COACH)
    athlete = _user(UserRole.ATHLETE)
    catalog = ExerciseCatalog(
        name="Press banca",
        muscle="CHEST",
        equipment="Barra",
        rep_lo=6,
        rep_hi=10,
        target_rir=2,
        load_increment_kg=2.5,
    )
    session.add_all([coach, athlete, catalog])
    await session.flush()

    meso = Mesocycle(
        athlete_id=athlete.id,
        coach_id=coach.id,
        name="Push/Pull/Legs",
        total_weeks=6,
        current_week_index=0,
        aggressiveness="Media",
        status="active",
    )
    session.add(meso)
    await session.flush()

    mex = MesocycleExercise(
        mesocycle_id=meso.id,
        catalog_id=catalog.id,
        position=0,
        rep_lo=6,
        rep_hi=10,
        target_rir=2,
        load_increment_kg=2.5,
        starting_load_kg=60.0,
        starting_reps=8,
        starting_sets=3,
    )
    session.add(mex)
    await session.flush()
    return meso, mex



async def _session_exercise(session: AsyncSession) -> SessionExercise:
    meso, mex = await _meso_con_ejercicio(session)
    ts = TrainingSession(mesocycle_id=meso.id, week_number=1, day_label="Push A")
    session.add(ts)
    await session.flush()

    se = SessionExercise(
        session_id=ts.id,
        mesocycle_exercise_id=mex.id,
        position=0,
        planned_load_kg=60.0,
        planned_sets=3,
        policy_version="2026.09",
        why="sin senales para mover la carga",
    )
    session.add(se)
    await session.flush()
    return se


@pytest.mark.asyncio
async def test_el_client_id_impide_duplicar_un_set(session: AsyncSession) -> None:
    """El caso real: la cola sin senal reenvia el mismo set tres veces.

    Sin este UNIQUE el set contaria varias veces y el motor subiria la carga
    por un fantasma.
    """
    se = await _session_exercise(session)
    cid = str(uuid.uuid4())

    session.add(SetLog(client_id=cid, session_exercise_id=se.id, idx=0, reps="8", done=True))
    await session.flush()

    session.add(SetLog(client_id=cid, session_exercise_id=se.id, idx=1, reps="8", done=True))
    with pytest.raises(IntegrityError):
        await session.flush()



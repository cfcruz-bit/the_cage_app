@pytest.mark.asyncio
async def test_las_reps_se_guardan_como_texto(session: AsyncSession) -> None:
    """'8+2' de un myorep tiene que sobrevivir el viaje de ida y vuelta."""
    se = await _session_exercise(session)
    log = SetLog(
        client_id=str(uuid.uuid4()),
        session_exercise_id=se.id,
        idx=0,
        reps="8+2",
        sub_sets="8,2",
        done=True,
    )
    session.add(log)
    await session.flush()
    session.expunge(log)

    found = await session.get(SetLog, log.id)
    assert found is not None
    assert found.reps == "8+2"
    assert found.sub_sets == "8,2"


